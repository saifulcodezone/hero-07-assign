// Bengali digit conversion
export const toBengaliNumber = (num) => {
  const bn = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
  return String(num).replace(/\d/g, (d) => bn[d]);
};

// Price with comma
export const formatBengaliPrice = (num) => {
  const formatted = Number(num).toLocaleString("en-IN");
  return toBengaliNumber(formatted);
};

// Bangla date
export const getBanglaDate = () => {
  const today = new Date();
  const months = [
    "জানুয়ারি",
    "ফেব্রুয়ারি",
    "মার্চ",
    "এপ্রিল",
    "মে",
    "জুন",
    "জুলাই",
    "আগস্ট",
    "সেপ্টেম্বর",
    "অক্টোবর",
    "নভেম্বর",
    "ডিসেম্বর",
  ];
  const days = [
    "রবিবার",
    "সোমবার",
    "মঙ্গলবার",
    "বুধবার",
    "বৃহস্পতিবার",
    "শুক্রবার",
    "শনিবার",
  ];
  return `${days[today.getDay()]}, ${toBengaliNumber(today.getDate())} ${months[today.getMonth()]}, ${toBengaliNumber(today.getFullYear())}`;
};

// Unit display
export const getUnitLabel = (unit) => {
  const map = {
    kg: "প্রতি কেজি",
    litre: "প্রতি লিটার",
    dozen: "প্রতি ডজন",
    piece: "প্রতি পিস",
  };
  return map[unit] || `প্রতি ${unit}`;
};

